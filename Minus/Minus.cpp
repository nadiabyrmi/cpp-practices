#include <iostream>
using namespace std;
int main()
{
	int n = 20;
	cout << " Your Integer Number Is : 20 " << endl;
	n--;
	cout << " now n is: " << n << endl;
	--n;
	cout << " now n is: " << n << endl;
	n -= 1;
	cout << " now n is: " << n << endl;
	cout << " now n is: " << n - 1 << endl;
	return 0;
}